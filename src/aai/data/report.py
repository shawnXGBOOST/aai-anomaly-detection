"""Dataset inspection: computes facts from the raw files and renders a Markdown report.

Nothing in the report is typed by hand. Every number is computed from the data on disk.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

from aai.data.labels import LabelError, LabelTable, intervals_to_mask
from aai.data.loader import SPACECRAFT_BY_N_FEATURES, channel_names, load_arrays


def channel_table(data_dir: str | Path, table: LabelTable) -> pd.DataFrame:
    """One row per channel file with shape, quality and label statistics."""
    rows = []
    for name in channel_names(data_dir):
        train, test = load_arrays(data_dir, name)
        entry = table.usable.get(name)
        if entry is not None:
            status = "ok"
        elif name in table.ambiguous:
            status = "ambiguous"
        else:
            status = "unlabeled"

        in_bounds, anomalous = True, 0
        if entry is not None:
            try:
                anomalous = int(intervals_to_mask(entry.intervals, len(test)).sum())
            except LabelError:
                in_bounds = False

        tele_train, tele_test = train[:, 0], test[:, 0]
        rows.append(
            {
                "channel": name,
                "spacecraft": entry.spacecraft
                if entry
                else SPACECRAFT_BY_N_FEATURES.get(train.shape[1], "unknown"),
                "n_features": train.shape[1],
                "train_len": len(train),
                "test_len": len(test),
                "train_nonfinite": int((~np.isfinite(train)).sum()),
                "test_nonfinite": int((~np.isfinite(test)).sum()),
                "train_constant_telemetry": bool(np.nanstd(tele_train) == 0),
                "train_constant_columns": int((np.nanstd(train, axis=0) == 0).sum()),
                "test_outside_train_range": bool(
                    np.nanmin(tele_test) < np.nanmin(tele_train)
                    or np.nanmax(tele_test) > np.nanmax(tele_train)
                ),
                "label_status": status,
                "n_intervals": len(entry.intervals) if entry else 0,
                "intervals_in_bounds": in_bounds,
                "label_length_matches": (entry.num_values == len(test)) if entry else None,
                "anomalous_points": anomalous,
            }
        )
    return pd.DataFrame(rows)


def _range(series: pd.Series) -> str:
    return f"{int(series.min())} / {int(series.median())} / {int(series.max())}"


def render_report(df: pd.DataFrame, table: LabelTable) -> str:
    """Render the Markdown data report from the channel table and the parsed labels."""
    scored = df[df.label_status == "ok"]
    lines: list[str] = ["# Data report: NASA SMAP / MSL telemetry", ""]
    lines += [
        "Generated by `aai inspect-data` from the raw telemanom files. "
        "Every number below is computed from the data, not typed by hand.",
        "",
    ]

    # Overview
    lines += ["## Overview", ""]
    lines.append(f"- Channels with a train and a test file: **{len(df)}**")
    for (craft, n_feat), count in df.groupby(["spacecraft", "n_features"]).size().items():
        lines.append(f"- {craft}: {count} channels with {n_feat} features each")
    lines.append(
        "- Column 0 of every array is the telemetry value; the other columns are command flags."
    )
    lines += [
        "",
        "Series length (min / median / max):",
        "",
        f"- train: {_range(df.train_len)}",
        f"- test: {_range(df.test_len)}",
        "",
    ]

    # Data quality
    const = df.channel[df.train_constant_telemetry].tolist()
    outside = int(df.test_outside_train_range.sum())
    lines += ["## Data quality", ""]
    lines.append(
        f"- Non-finite values: {int(df.train_nonfinite.sum())} in train, "
        f"{int(df.test_nonfinite.sum())} in test"
    )
    lines.append(
        f"- Channels whose telemetry is constant in train: **{len(const)}** ({', '.join(const)})"
    )
    lines.append(
        "- Channels whose test telemetry leaves the train min/max range: "
        f"**{outside}** of {len(df)}"
    )
    lines.append("")

    # Labels
    unlabeled = df.channel[df.label_status == "unlabeled"].tolist()
    no_data = sorted((set(table.usable) | set(table.ambiguous)) - set(df.channel))
    lengths: list[int] = []
    starts: list[int] = []
    classes: Counter[str] = Counter()
    overlaps = ends_at_last = past_end = 0
    longest = 0.0
    for entry in table.usable.values():
        spans = sorted(entry.intervals)
        overlaps += sum(spans[i][1] >= spans[i + 1][0] for i in range(len(spans) - 1))
        starts.append(spans[0][0] if spans else entry.num_values)
        for start, end in entry.intervals:
            lengths.append(end - start + 1)
            longest = max(longest, (end - start + 1) / entry.num_values)
            ends_at_last += end == entry.num_values - 1
            past_end += end >= entry.num_values
        if len(entry.classes) == len(entry.intervals):
            classes.update(entry.classes)

    lines += ["## Labels", ""]
    lines.append(
        f"- Rows in `labeled_anomalies.csv`: {table.n_rows} "
        f"({len(table.usable) + len(table.ambiguous)} distinct channels)"
    )
    lines.append(f"- Channels with conflicting duplicate rows: **{len(table.ambiguous)}**")
    for name, reason in table.ambiguous.items():
        lines.append(f"  - `{name}`: {reason}")
    lines.append(
        f"- Channel files with no label row: **{len(unlabeled)}** ({', '.join(unlabeled)})"
    )
    lines.append(f"- Labeled channels with no data files: {len(no_data)}")
    mismatch = int((~scored.label_length_matches.astype(bool)).sum())
    lines.append(f"- Labeled channels whose `num_values` differs from the test length: {mismatch}")
    length_summary = (
        f"{min(lengths)} / {int(np.median(lengths))} / {max(lengths)}" if lengths else "n/a"
    )
    lines.append(
        f"- Anomaly intervals (scored channels): **{len(lengths)}**, "
        f"length min / median / max = {length_summary}"
    )
    lines.append(f"- Interval classes: {dict(classes)}")
    lines.append(f"- Overlapping intervals inside one channel: {overlaps}")
    lines.append(
        f"- Intervals ending exactly at the last index: {ends_at_last}; "
        f"intervals ending past the series: {past_end}"
    )
    earliest = min(starts) if starts else None
    median_start = int(np.median(starts)) if starts else None
    lines.append(f"- Longest single interval covers {longest:.0%} of its test series")
    lines.append(
        f"- Earliest anomaly starts at index {earliest} (median over channels: {median_start})"
    )
    lines += ["", "Anomalous share of test points, scored channels only:", ""]
    share = scored.groupby("spacecraft")[["anomalous_points", "test_len"]].sum()
    for craft, row in share.iterrows():
        lines.append(
            f"- {craft}: {int(row.anomalous_points)} of {int(row.test_len)} points "
            f"({row.anomalous_points / row.test_len:.1%})"
        )
    lines.append("")

    # Decisions
    counts = scored.spacecraft.value_counts().sort_index()
    breakdown = ", ".join(f"{craft}: {n}" for craft, n in counts.items())
    lines += ["## Decisions this implies", ""]
    lines.append(
        f"- **Scored set:** {len(scored)} channels ({breakdown}). Excluded: "
        + (", ".join(f"`{n}`" for n in [*table.ambiguous, *unlabeled]) or "none")
        + ". Their labels are ambiguous or missing, so any score on them would be unverifiable."
    )
    if ends_at_last > 0 and past_end == 0:
        verdict = "which is consistent with inclusive ends"
    else:
        verdict = "so the data alone does not settle whether ends are inclusive"
    lines.append(
        f"- **Interval convention:** interval ends are treated as inclusive. {ends_at_last} "
        f"intervals end exactly at the last index and {past_end} go past it, {verdict}."
    )
    lines.append(
        f"- **Scaling:** {len(const)} channels have constant train telemetry and need a variance "
        f"floor. Test telemetry leaves the train range in {outside} of {len(df)} channels, so "
        "inputs must not be clipped to the train range."
    )
    lines.append(
        f"- **Warm-up:** the earliest anomaly starts at index {earliest}, so rolling features "
        "and adaptive baselines must be warmed up with the end of the train series."
    )
    lines.append(
        f"- **Metrics:** the longest single interval covers {longest:.0%} of its series, so "
        "point-level metrics are reported only next to event-level metrics."
    )
    lines += [
        "",
        "## Limitations",
        "",
        "- Labels come from the original benchmark release and cannot be verified here.",
        "- The benchmark treats every train series as anomaly-free; the data cannot confirm it.",
        "- Constant-telemetry and range statistics use column 0 only; flags are not analysed.",
        "",
    ]
    return "\n".join(lines)
